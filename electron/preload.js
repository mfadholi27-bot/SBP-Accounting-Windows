const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("sbpDesktop", {
  version: () => ipcRenderer.invoke("app:version"),
  summary: () => ipcRenderer.invoke("db:summary"),
  backup: () => ipcRenderer.invoke("db:backup"),
  automaticBackup: () => ipcRenderer.invoke("db:auto-backup"),
  listAccounts: (keyword) => ipcRenderer.invoke("accounts:list", keyword || ""),
  saveAccount: (account) => ipcRenderer.invoke("accounts:save", account),
  setAccountActive: (payload) => ipcRenderer.invoke("accounts:set-active", payload),
  deleteAccount: (id) => ipcRenderer.invoke("accounts:delete", id),
  listJournals: (filters) => ipcRenderer.invoke("journals:list", filters || {}),
  saveJournal: (journal) => ipcRenderer.invoke("journals:save", journal),
  importBulkJournals: (payload) => ipcRenderer.invoke("journals:import-bulk", payload),
  deleteDraftJournal: (id) => ipcRenderer.invoke("journals:delete-draft", id),
  listBudgets: (year) => ipcRenderer.invoke("budgets:list", year),
  saveBudget: (payload) => ipcRenderer.invoke("budgets:save", payload),
  deleteBudget: (payload) => ipcRenderer.invoke("budgets:delete", payload),
  importAccounts: (payload) => ipcRenderer.invoke("imports:accounts", payload),
  listNptrans: (filters) => ipcRenderer.invoke("nptrans:list", filters),
  importNptrans: (payload) => ipcRenderer.invoke("nptrans:import", payload),
  importOpeningBalances: (payload) => ipcRenderer.invoke("imports:opening-balances", payload),
  listOpeningBalances: (period) => ipcRenderer.invoke("opening:list", period),
  saveOpeningBalance: (payload) => ipcRenderer.invoke("opening:save", payload),
  listDebitNotes: (filters) => ipcRenderer.invoke("debit-notes:list", filters),
  saveDebitNote: (payload) => ipcRenderer.invoke("debit-notes:save", payload),
  postDebitNote: (id) => ipcRenderer.invoke("debit-notes:post", id),
  cancelDebitNote: (payload) => ipcRenderer.invoke("debit-notes:cancel", payload),
  listPeriods: () => ipcRenderer.invoke("periods:list"),
  openPeriod: (payload) => ipcRenderer.invoke("periods:open", payload),
  closePeriod: (payload) => ipcRenderer.invoke("periods:close", payload),
  reopenPeriod: (payload) => ipcRenderer.invoke("periods:reopen", payload),
  trialBalance: (payload) => ipcRenderer.invoke("reports:trial-balance", payload),
  ledgerReport: (payload) => ipcRenderer.invoke("reports:ledger", payload),
  incomeSummary: (payload) => ipcRenderer.invoke("reports:income-summary", payload),
  incomeStatement: (payload) => ipcRenderer.invoke("reports:income-statement", payload),
  balanceSheet: (payload) => ipcRenderer.invoke("reports:balance-sheet", payload),
  exportAudit: () => ipcRenderer.invoke("audit:export"),
  runValidation: () => ipcRenderer.invoke("validation:run"),
  listAudit: (payload) => ipcRenderer.invoke("audit:list", payload),
  getPrintSettings: () => ipcRenderer.invoke("print-settings:get"),
  savePrintSettings: (payload) => ipcRenderer.invoke("print-settings:save", payload),
  createArchive: (payload) => ipcRenderer.invoke("archive:create", payload),
  listArchives: () => ipcRenderer.invoke("archive:list"),
  readArchive: () => ipcRenderer.invoke("archive:read"),
  restoreDatabase: () => ipcRenderer.invoke("db:restore"),
  importV19Backup: (payload) => ipcRenderer.invoke("migration:import-v19", payload),
  reverseJournal: (payload) => ipcRenderer.invoke("journals:reverse", payload),
  createCorrectionDraft: (payload) => ipcRenderer.invoke("journals:correction-draft", payload)
});
